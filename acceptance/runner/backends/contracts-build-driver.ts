// Contracts-build phase driver (RM-01 plan, C13).
//
// Plugs into the same `PhaseDriver` interface the C12 stub / agent
// drivers use, but for the projectless contract slice ALSO emits a
// realistic-but-deterministic OpenAPI 3.1 + JSON Schema bundle into
// the hub's baseline `contracts/` tree. Implementation slices keep
// the deterministic stub driver via the C13 `phaseDriverFor` per-
// slice dispatch on `ScriptedExecuteBackend` /
// `ScriptedFinalizeBackend`.
//
// Why "deterministic but real":
//   * the YAML must pass the contracts WASI tool's checks (RFC-12
//     §Validation rules: SemVer `info.version`, kebab-case
//     `info.x-specify-id`, no broken `$ref`s, etc.) — so the
//     `contract-slice-yaml-validates-via-tool` assertion can
//     actually run the validator and assert `ok: true`,
//   * the bodies stay byte-for-byte stable so a CI re-run never
//     produces a diff,
//   * each file carries a `# STUB:` header marking it as a
//     deterministic test fixture (not real `/spec:build` output) —
//     mirroring the C12 stub `STUB:`-marker convention.
//
// The driver writes contract YAMLs directly into `<hubDir>/contracts/
// {http,schemas}/`. The contract slice is projectless in the loop
// driver, so for the contract slice the `driveSliceWithBodies`
// helper writes only `.specify/specs/<slice>/` + `.specify/archive/
// <slice>/` (no git involvement). Adding `<hubDir>/contracts/*.yaml`
// is a pure file-write that the C13 assertion handlers then probe.

