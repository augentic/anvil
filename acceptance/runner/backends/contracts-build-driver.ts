/**
 * Contracts-build phase driver. For the contract slice (projectless,
 * capability=contracts) it runs the standard define+merge lifecycle
 * via `driveSliceWithBodies` AND writes the OpenAPI/JSON-Schema
 * bundle into `<hubDir>/contracts/`. For non-contract slices the
 * driver still works (delegates to the stub bodies) — though the
 * C13 backend uses `phaseDriverFor` so this driver only ever runs
 * for the contract slice in practice. Keeping the fall-through path
 * defensive means a misconfigured backend still produces a sensible
 * action log instead of crashing.
 */
export class ContractsBuildPhaseDriver implements PhaseDriver {
  readonly name = "contracts-build" as const;

  async driveSlice(opts: DriveSliceOpts): Promise<DriveSliceResult> {
    const result = await driveSliceWithBodies(opts, stubBodyFactory);

    const isContractSlice = opts.project === null &&
      opts.capabilityName === "contracts";
    if (!isContractSlice) {
      return result;
    }

    const written = await writeContractBundle(opts.hubDir);
    result.actions.push({
      ts: new Date().toISOString(),
      phase: "build",
      slice: opts.sliceName,
      action: "contracts-build-emit-yaml",
      artifacts: written.map((p) => `contracts/${p}`),
    });
    return result;
  }
}

/**
 * Write every `CONTRACT_YAML_PATHS` entry under `<hubDir>/contracts/`.
 * Returns the relative paths actually written (always the full set
 * for now; the helper is structured so a future amendment can vary
 * by capability brief without changing the call site).
 */
async function writeContractBundle(hubDir: string): Promise<string[]> {
  const written: string[] = [];
  for (const rel of CONTRACT_YAML_PATHS) {
    const abs = join(hubDir, "contracts", rel);
    await ensureDir(dirname(abs));
    await Deno.writeTextFile(abs, CONTRACT_BODIES[rel]);
    written.push(rel);
  }
  return written;
}
